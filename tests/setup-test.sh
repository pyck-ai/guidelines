#!/bin/sh
# Tests ./setup.sh against throwaway HOME directories: sh tests/setup-test.sh
# Prints PASS or FAIL per check and exits 1 if any check failed. Never touches
# the real HOME.
set -u

REPO=$(cd -P "$(dirname "$0")/.." && pwd -P)
ROOT=${TMPDIR:-/tmp}/guidelines-setup-test.$$
CFG=.config/opencode/config.json
NEWDIR=.agents/skills
# Where our links used to be placed; setup.sh removes them and keeps the dirs.
# OLD1 is opencode's skills dir: it still gets links, but only for skills tagged
# opencode, and none of the real ones is.
OLD1=.config/opencode/skills
OLD2=.claude/skills
USERCFG=.config/opencode/opencode.json
MARKER='// Generated by pyck-ai/guidelines setup.sh. Do not edit: rerun ./setup.sh. Remove with ./setup.sh uninstall.'
LEGACY1='// Generated by pyck-ai/standards setup.sh, do not edit'
LEGACY2='// Org guidelines layer for opencode: written by hand'
SETUP_ENV=
SCRIPT=
FAILS=0
CASE=0
H=
OUT=
RC=0

pass() { printf 'PASS %s\n' "$1"; }
fail() {
	printf 'FAIL %s\n' "$1"
	FAILS=$((FAILS + 1))
}
# check DESC CMD...: PASS if CMD succeeds.
check() {
	_desc=$1
	shift
	if "$@"; then pass "$_desc"; else fail "$_desc"; fi
}

# new_home: a fresh HOME in $H, the output file in $OUT.
new_home() {
	CASE=$((CASE + 1))
	H=$ROOT/home$CASE
	OUT=$ROOT/out$CASE
	mkdir -p "$H"
	SETUP_ENV=
	SCRIPT=
}

# setup ARGS...: run setup.sh with HOME=$H (plus the VAR=value words in
# $SETUP_ENV); output in $OUT, exit code in $RC. $SCRIPT overrides the script.
setup() {
	# shellcheck disable=SC2086
	env HOME="$H" $SETUP_ENV sh "${SCRIPT:-$REPO/setup.sh}" "$@" >"$OUT" 2>&1
	RC=$?
}

snapshot() { ls -lAR "$H"; }
says() { grep -F -q -- "$1" "$OUT"; }
says_line() { grep -F -x -q -- "$1" "$OUT"; }
not() { ! "$@"; }
rc_is() { [ "$RC" -eq "$1" ]; }
absent() { ! [ -e "$1" ] && ! [ -L "$1" ]; }
is_link_to() { [ -L "$1" ] && [ "$(readlink "$1")" = "$2" ]; }
first_line_is() { [ "$(head -n 1 "$1")" = "$2" ]; }
is_real_dir() { [ -d "$1" ] && [ ! -L "$1" ]; }
same_text() { [ "$(cat "$1")" = "$2" ]; }

# links_to BASE [SKIP]: every skill is linked into ~/.agents/skills as
# BASE/skills/<n>, except SKIP (a path).
links_to() {
	for _s in $SKILLS; do
		[ "$H/$NEWDIR/$_s" = "${2:-}" ] && continue
		is_link_to "$H/$NEWDIR/$_s" "$1/skills/$_s" || return 1
	done
}
# links_ok [SKIP]: every skill is linked through ~/.pyck/guidelines.
links_ok() { links_to "$H/.pyck/guidelines" "${1:-}"; }
# links_into_repo: some skill link still points into the real checkout path.
links_into_repo() {
	for _l in "$H/$NEWDIR"/*; do
		case $(readlink "$_l") in "$REPO"/*) return 0 ;; esac
	done
	return 1
}
# plant_links BASE [DIR...]: make those links in each DIR (default:
# ~/.agents/skills), as an older install or another checkout would.
plant_links() {
	_base=$1
	shift
	[ "$#" -gt 0 ] || set -- "$NEWDIR"
	for _d in "$@"; do
		mkdir -p "$H/$_d"
		for _s in $SKILLS; do
			ln -s "$_base/skills/$_s" "$H/$_d/$_s"
		done
	done
}
# plant_cfg [FILE]: a config.json that an older setup.sh generated (default
# ~/.config/opencode/config.json).
plant_cfg() {
	_f=${1:-$H/$CFG}
	mkdir -p "$(dirname "$_f")"
	printf '%s\n{}\n' "$MARKER" >"$_f"
}
no_links() {
	for _s in $SKILLS; do
		absent "$H/$NEWDIR/$_s" || return 1
	done
}
# old_links_gone: none of our skill links is left in the two old dirs.
old_links_gone() {
	for _d in "$OLD1" "$OLD2"; do
		for _s in $SKILLS; do
			absent "$H/$_d/$_s" || return 1
		done
	done
}

SKILLS=
N=0
for _p in "$REPO"/skills/*/; do
	_p=${_p%/}
	SKILLS="$SKILLS ${_p##*/}"
	N=$((N + 1))
done
# shellcheck disable=SC2086
set -- $SKILLS
S1=$1

mkdir -p "$ROOT" || exit 1
trap 'rm -rf "$ROOT"' EXIT

echo "== dry run"
new_home
plant_links "$REPO" "$OLD1" "$OLD2"
plant_cfg
before=$(snapshot)
setup --dry-run
after=$(snapshot)
check "exit 0" rc_is 0
check "changes nothing on disk" [ "$before" = "$after" ]
check "says it is a dry run" says "Dry run: install"
# home link, N new links, the old config.json, N old links in each old dir
check "reports what it would change" says "dry run, install: $((N * 3 + 2)) changed"
check "reports the new links" says "linked    ~/$NEWDIR/$S1 -> ~/.pyck/guidelines/skills/$S1"
check "reports the old config links removed" says "removed   ~/$OLD1/$S1"
check "reports the old .claude links removed" says "removed   ~/$OLD2/$S1"
check "reports the old config.json removed" says "removed   ~/$CFG"
check "reports no conflict" says " 0 conflicts"
check "removes no directory" not says_line "removed   ~/.claude/skills"

echo "== first install"
new_home
setup
check "exit 0" rc_is 0
check "every skill is linked into ~/.agents/skills" links_ok
check "no ~/.claude is created" absent "$H/.claude"
check "no opencode skills dir is created" absent "$H/$OLD1"
check "no config.json is written" absent "$H/$CFG"
check "no opencode.json is seeded" absent "$H/$USERCFG"
check "no opencode config dir is created" absent "$H/.config"
check "the .pyck/guidelines path links to the checkout" is_link_to "$H/.pyck/guidelines" "$REPO"
check "reported as linked" says "linked    ~/.pyck/guidelines -> $REPO"
echo "== second install"
setup
check "exit 0" rc_is 0
check "0 changed" says " 0 changed,"
check "the .pyck/guidelines path is ok" says "ok        ~/.pyck/guidelines"

echo "== uninstall"
ln -s "$ROOT/elsewhere" "$H/$NEWDIR/foreign"
echo notes >"$H/$NEWDIR/notes.txt"
setup uninstall
check "exit 0" rc_is 0
check "our links are gone" no_links
check "dir ~/.agents/skills stays" is_real_dir "$H/$NEWDIR"
check "dir ~/.agents stays" is_real_dir "$H/.agents"
check "our ~/.pyck/guidelines link is gone" absent "$H/.pyck/guidelines"
check "the .pyck directory itself stays" is_real_dir "$H/.pyck"
check "foreign link stays" is_link_to "$H/$NEWDIR/foreign" "$ROOT/elsewhere"
check "unmarked file stays" same_text "$H/$NEWDIR/notes.txt" notes
setup uninstall
check "second uninstall: exit 0" rc_is 0
check "second uninstall: 0 changed" says " 0 changed,"

echo "== real folder at ~/.pyck/guidelines"
new_home
mkdir -p "$H/.pyck/guidelines"
echo mine >"$H/.pyck/guidelines/file"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/.pyck/guidelines exists and is not a link"
check "folder is untouched" same_text "$H/.pyck/guidelines/file" mine
check "folder is still a real directory" is_real_dir "$H/.pyck/guidelines"
check "explains the fix" says "uninstall"
check "nothing else is installed" no_links
check "no config.json is written" absent "$H/$CFG"
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: reported as kept" says "kept      ~/.pyck/guidelines"
check "uninstall: folder stays" same_text "$H/.pyck/guidelines/file" mine

echo "== foreign link at ~/.pyck/guidelines"
new_home
mkdir -p "$H/.pyck"
ln -s "$ROOT/elsewhere" "$H/.pyck/guidelines"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/.pyck/guidelines links to"
check "foreign link is untouched" is_link_to "$H/.pyck/guidelines" "$ROOT/elsewhere"
check "nothing else is installed" no_links
check "no config.json is written" absent "$H/$CFG"
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: foreign link stays" is_link_to "$H/.pyck/guidelines" "$ROOT/elsewhere"

echo "== ~/.pyck/guidelines is this checkout"
# A link to the repo stands in for a clone made at ~/.pyck/guidelines: the
# path resolves to the repo, so setup.sh creates nothing there.
new_home
mkdir -p "$H/.pyck"
ln -s "$REPO" "$H/.pyck/guidelines"
setup
check "exit 0" rc_is 0
check "reported as ok" says "ok        ~/.pyck/guidelines"
check "link is unchanged" is_link_to "$H/.pyck/guidelines" "$REPO"

echo "== ~/.pyck/guidelines resolves to this checkout"
# The link text differs from $REPO but resolves to it, as a clone would.
new_home
mkdir -p "$H/.pyck"
ln -s "$REPO/." "$H/.pyck/guidelines"
setup
check "exit 0" rc_is 0
check "reported as this checkout" says "ok        ~/.pyck/guidelines (this checkout)"
check "link is unchanged" is_link_to "$H/.pyck/guidelines" "$REPO/."
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: not ours by text, so kept" says "kept      ~/.pyck/guidelines"

echo "== migration from links to the checkout path"
new_home
plant_links "$REPO"
setup
check "exit 0" rc_is 0
check "old links are relinked" says "relinked  ~/$NEWDIR/$S1 -> ~/.pyck/guidelines/skills/$S1"
check "every skill now links through ~/.pyck/guidelines" links_ok
check "no skill link points at the checkout path" not links_into_repo
check "the home link is made" is_link_to "$H/.pyck/guidelines" "$REPO"
setup
check "re-run: 0 changed" says " 0 changed,"

echo "== clone in place"
# The checkout itself lives at ~/.pyck/guidelines: nothing is linked there.
new_home
mkdir -p "$H/.pyck/guidelines"
cp -R "$REPO/skills" "$H/.pyck/guidelines/skills"
cp "$REPO/setup.sh" "$H/.pyck/guidelines/setup.sh"
SCRIPT=$H/.pyck/guidelines/setup.sh
setup
check "exit 0" rc_is 0
check "reported as this checkout" says "ok        ~/.pyck/guidelines (this checkout)"
check "still a real directory" is_real_dir "$H/.pyck/guidelines"
check "every skill links through ~/.pyck/guidelines" links_ok
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: our links are gone" no_links
check "uninstall: the clone stays" is_real_dir "$H/.pyck/guidelines"
check "uninstall: reported as kept" says "kept      ~/.pyck/guidelines"

echo "== ~/.pyck/guidelines belongs to another checkout"
new_home
mkdir -p "$ROOT/other/skills" "$H/.pyck"
for _s in $SKILLS; do mkdir -p "$ROOT/other/skills/$_s"; done
ln -s "$ROOT/other" "$H/.pyck/guidelines"
plant_links "$H/.pyck/guidelines"
before=$(snapshot)
setup
after=$(snapshot)
check "install: exit 1" rc_is 1
check "install: reported as conflict" says "conflict  ~/.pyck/guidelines links to"
check "install: changes nothing" [ "$before" = "$after" ]
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: the link stays" is_link_to "$H/.pyck/guidelines" "$ROOT/other"
check "uninstall: links through it stay" links_ok
check "uninstall: nothing removed" says " 0 changed,"

echo "== an exported PYCK_HOME is ignored"
new_home
SETUP_ENV="PYCK_HOME=$H/custom"
setup
check "exit 0" rc_is 0
check "the home link is still ~/.pyck/guidelines" is_link_to "$H/.pyck/guidelines" "$REPO"
check "the exported directory is not created" absent "$H/custom"
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: the home link is gone" absent "$H/.pyck/guidelines"
check "uninstall: the exported directory is not created" absent "$H/custom"

echo "== real folder at a target"
new_home
mkdir -p "$H/$NEWDIR/$S1"
echo mine >"$H/$NEWDIR/$S1/file"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/$NEWDIR/$S1 exists and is not a link"
check "folder is untouched" same_text "$H/$NEWDIR/$S1/file" mine
check "folder is still a real directory" is_real_dir "$H/$NEWDIR/$S1"
check "every other link is made" links_ok "$H/$NEWDIR/$S1"

echo "== foreign symlink at a target"
new_home
mkdir -p "$H/$NEWDIR"
ln -s "$ROOT/elsewhere" "$H/$NEWDIR/$S1"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/$NEWDIR/$S1 links to"
check "foreign link is untouched" is_link_to "$H/$NEWDIR/$S1" "$ROOT/elsewhere"
check "every other link is made" links_ok "$H/$NEWDIR/$S1"

echo "== stale link into the checkout"
new_home
mkdir -p "$H/$NEWDIR"
ln -s "$REPO/skills/gone" "$H/$NEWDIR/gone"
setup
check "exit 0" rc_is 0
check "stale link is removed" absent "$H/$NEWDIR/gone"
check "reported as removed" says "removed   ~/$NEWDIR/gone"
check "every skill is linked" links_ok

echo "== migration from opencode's skills dir and ~/.claude/skills"
echo "-- only our links"
new_home
plant_links "$REPO" "$OLD1" "$OLD2"
mkdir -p "$H/.claude/synced"
setup
check "exit 0" rc_is 0
check "every skill is linked into ~/.agents/skills" links_ok
check "our old links are gone" old_links_gone
check "line for an old link is reported" says "removed   ~/$OLD1/$S1"
check "dir opencode's skills stays" is_real_dir "$H/$OLD1"
check "dir ~/.claude/skills stays" is_real_dir "$H/$OLD2"
check "dir ~/.claude/synced stays" is_real_dir "$H/.claude/synced"
check "no directory is reported removed" not says_line "removed   ~/$OLD1"
setup
check "re-run: 0 changed" says " 0 changed,"
echo "-- links through ~/.pyck/guidelines"
new_home
mkdir -p "$H/.pyck"
ln -s "$REPO" "$H/.pyck/guidelines"
plant_links "$H/.pyck/guidelines" "$OLD1" "$OLD2"
setup
check "exit 0" rc_is 0
check "our old links are gone" old_links_gone
check "dir ~/.claude/skills stays" is_real_dir "$H/$OLD2"
echo "-- foreign link and foreign file"
new_home
plant_links "$REPO" "$OLD1" "$OLD2"
ln -s "$ROOT/elsewhere" "$H/$OLD1/foreign"
echo notes >"$H/$OLD1/notes.txt"
ln -s "$ROOT/elsewhere" "$H/$OLD2/foreign"
echo notes >"$H/$OLD2/notes.txt"
setup
check "exit 0" rc_is 0
check "our old links are gone" old_links_gone
check "foreign link stays in opencode's skills dir" is_link_to "$H/$OLD1/foreign" "$ROOT/elsewhere"
check "foreign link stays in .claude" is_link_to "$H/$OLD2/foreign" "$ROOT/elsewhere"
check "foreign file stays in opencode's skills dir" same_text "$H/$OLD1/notes.txt" notes
check "foreign file stays in .claude" same_text "$H/$OLD2/notes.txt" notes
check "every skill is linked into ~/.agents/skills" links_ok
echo "-- foreign entries in ~/.agents/skills"
new_home
mkdir -p "$H/$NEWDIR"
ln -s "$ROOT/elsewhere" "$H/$NEWDIR/foreign"
echo notes >"$H/$NEWDIR/notes.txt"
setup
check "exit 0" rc_is 0
check "foreign link stays" is_link_to "$H/$NEWDIR/foreign" "$ROOT/elsewhere"
check "foreign file stays" same_text "$H/$NEWDIR/notes.txt" notes
check "every skill is linked" links_ok
echo "-- empty old dirs are never removed"
new_home
mkdir -p "$H/$OLD1" "$H/$OLD2"
setup
check "exit 0" rc_is 0
check "dir opencode's skills stays" is_real_dir "$H/$OLD1"
check "dir ~/.claude/skills stays" is_real_dir "$H/$OLD2"
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: opencode's skills dir stays" is_real_dir "$H/$OLD1"
check "uninstall: ~/.claude/skills stays" is_real_dir "$H/$OLD2"
echo "-- under XDG_CONFIG_HOME"
new_home
SETUP_ENV="XDG_CONFIG_HOME=$H/xdg"
mkdir -p "$H/xdg/opencode/skills"
for _s in $SKILLS; do ln -s "$REPO/skills/$_s" "$H/xdg/opencode/skills/$_s"; done
ln -s "$ROOT/elsewhere" "$H/xdg/opencode/skills/foreign"
setup
check "exit 0" rc_is 0
check "our links are gone from the XDG dir" absent "$H/xdg/opencode/skills/$S1"
check "foreign link stays in the XDG dir" is_link_to "$H/xdg/opencode/skills/foreign" "$ROOT/elsewhere"
check "every skill is linked into ~/.agents/skills" links_ok
echo "-- uninstall"
new_home
plant_links "$REPO" "$OLD1" "$OLD2"
plant_links "$REPO"
setup uninstall
check "exit 0" rc_is 0
check "our old links are gone" old_links_gone
check "our links are gone" no_links
check "dir ~/.agents stays" is_real_dir "$H/.agents"
check "dir ~/.claude/skills stays" is_real_dir "$H/$OLD2"
echo "-- a dry run changes nothing"
new_home
plant_links "$REPO" "$OLD1" "$OLD2"
mkdir -p "$H/.opencode"
before=$(snapshot)
setup --dry-run
check "install: exit 0" rc_is 0
check "install: nothing changed" [ "$before" = "$(snapshot)" ]
setup uninstall --dry-run
check "uninstall: exit 0" rc_is 0
check "uninstall: nothing changed" [ "$before" = "$(snapshot)" ]

echo "== skills sorted by metadata.harness"
# A sandbox copy of the repo ($FX) with fixture skills, so that the real
# skills/ is never touched. The copy is built from scratch with real files.
FX=$ROOT/fx
OCDIR=.config/opencode/skills
# new_fx: a fresh sandbox repo in $FX; run it after new_home, which resets SCRIPT.
new_fx() {
	rm -rf "$FX"
	mkdir -p "$FX"
	cp "$REPO/setup.sh" "$FX/setup.sh"
	cp -R "$REPO/skills" "$FX/skills"
	SCRIPT=$FX/setup.sh
}
# fixture NAME TEXT: skills/NAME/SKILL.md in the sandbox repo (TEXT as printf %b).
fixture() {
	mkdir -p "$FX/skills/$1"
	printf '%b' "$2" >"$FX/skills/$1/SKILL.md"
}
# retag NAME HARNESS: rewrite a fixture with another harness.
retag() { fixture "$1" "---\\nname: $1\\nmetadata:\\n  harness: $2\\n---\\n"; }
# link_in NAME DIR: NAME is linked through ~/.pyck/guidelines into DIR (under $H).
link_in() { is_link_to "$H/$2/$1" "$H/.pyck/guidelines/skills/$1"; }

new_home
new_fx
fixture oc '---\nname: oc\nmetadata:\n  harness: opencode\n---\n'
fixture gq '---\nname: gq\nmetadata:\n  harness: "generic"\n---\n'
fixture oq "---\nname: oq\nmetadata:\n  harness: 'opencode'\n---\n"
setup
check "exit 0" rc_is 0
check "an opencode skill lands in opencode's skills dir" link_in oc "$OCDIR"
check "an opencode skill is not in ~/.agents/skills" absent "$H/$NEWDIR/oc"
check "a double-quoted generic skill lands in ~/.agents/skills" link_in gq "$NEWDIR"
check "a double-quoted generic skill is not in opencode's skills dir" absent "$H/$OCDIR/gq"
check "a single-quoted opencode skill lands in opencode's skills dir" link_in oq "$OCDIR"
check "the real skills land in ~/.agents/skills" links_ok
check "reports the opencode link" says "linked    ~/$OCDIR/oc -> ~/.pyck/guidelines/skills/oc"
setup
check "re-run: 0 changed" says " 0 changed,"
before=$(snapshot)
setup --dry-run
check "dry run: exit 0" rc_is 0
check "dry run: nothing changed" [ "$before" = "$(snapshot)" ]
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: the opencode link is gone" absent "$H/$OCDIR/oc"
check "uninstall: the single-quoted link is gone" absent "$H/$OCDIR/oq"
check "uninstall: the generic link is gone" absent "$H/$NEWDIR/gq"
check "uninstall: the real skills are gone" no_links
check "uninstall: opencode's skills dir stays" is_real_dir "$H/$OCDIR"
check "uninstall: ~/.agents/skills stays" is_real_dir "$H/$NEWDIR"

echo "-- under XDG_CONFIG_HOME"
new_home
new_fx
SETUP_ENV="XDG_CONFIG_HOME=$H/xdg"
fixture oc '---\nname: oc\nmetadata:\n  harness: opencode\n---\n'
setup
check "exit 0" rc_is 0
check "an opencode skill lands below XDG_CONFIG_HOME" link_in oc xdg/opencode/skills
check "nothing lands in ~/.config" absent "$H/.config"
check "the real skills land in ~/.agents/skills" links_ok
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: the opencode link is gone" absent "$H/xdg/opencode/skills/oc"

echo "-- a missing or unknown harness"
new_home
new_fx
fixture none '---\nname: none\ndescription: x\n---\n'
fixture bad '---\nname: bad\nmetadata:\n  harness: claude\n---\n'
fixture flat '---\nname: flat\nharness: generic\n---\n'
fixture empty '---\nname: empty\nmetadata:\n  harness:\n---\n'
fixture late '---\nname: late\n---\nmetadata:\n  harness: generic\n'
setup
check "exit 1" rc_is 1
check "a missing tag is a conflict" says "conflict  skills/none/SKILL.md has no metadata.harness"
check "an unknown value is a conflict" says "conflict  skills/bad/SKILL.md has unknown metadata.harness \"claude\""
check "a harness outside metadata is a conflict" says "conflict  skills/flat/SKILL.md has no metadata.harness"
check "an empty harness is a conflict" says "conflict  skills/empty/SKILL.md has no metadata.harness"
check "a harness after the frontmatter is a conflict" says "conflict  skills/late/SKILL.md has no metadata.harness"
check "reports 5 conflicts" says " 5 conflicts"
for _n in none bad flat empty late; do
	check "$_n is not linked into ~/.agents/skills" absent "$H/$NEWDIR/$_n"
	check "$_n is not linked into opencode's skills dir" absent "$H/$OCDIR/$_n"
done
check "the valid skills are still linked" links_ok
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: the valid skills are gone" no_links

echo "-- a changed harness"
new_home
new_fx
fixture mv '---\nname: mv\nmetadata:\n  harness: generic\n---\n'
setup
check "exit 0" rc_is 0
check "linked into ~/.agents/skills first" link_in mv "$NEWDIR"
retag mv opencode
setup
check "exit 0 after the change" rc_is 0
check "now linked into opencode's skills dir" link_in mv "$OCDIR"
check "the old link is pruned" absent "$H/$NEWDIR/mv"
check "the old link is reported removed" says "removed   ~/$NEWDIR/mv"
retag mv generic
setup
check "back to generic: linked into ~/.agents/skills" link_in mv "$NEWDIR"
check "back to generic: the opencode link is pruned" absent "$H/$OCDIR/mv"
setup
check "re-run: 0 changed" says " 0 changed,"
echo "-- a tag lost after install"
printf '%b' '---\nname: mv\n---\n' >"$FX/skills/mv/SKILL.md"
setup
check "exit 1" rc_is 1
check "the conflict is reported" says "conflict  skills/mv/SKILL.md has no metadata.harness"
check "the stale link is pruned" absent "$H/$NEWDIR/mv"

echo "== config.json written by an older setup.sh"
for _m in "$MARKER" "$LEGACY1" "$LEGACY2"; do
	new_home
	plant_cfg
	printf '%s\n{}\n' "$_m" >"$H/$CFG"
	before=$(snapshot)
	setup --dry-run
	check "dry run: exit 0 (${_m%%:*})" rc_is 0
	check "dry run: reports it removed (${_m%%:*})" says "removed   ~/$CFG"
	check "dry run: removes nothing (${_m%%:*})" [ "$before" = "$(snapshot)" ]
	setup
	check "install: exit 0 (${_m%%:*})" rc_is 0
	check "install: reported as removed (${_m%%:*})" says "removed   ~/$CFG"
	check "install: it is gone (${_m%%:*})" absent "$H/$CFG"
	check "install: no opencode.json is seeded (${_m%%:*})" absent "$H/$USERCFG"
	setup
	check "re-run: 0 changed (${_m%%:*})" says " 0 changed,"
done
new_home
setup
plant_cfg
setup uninstall --dry-run
check "uninstall dry run: exit 0" rc_is 0
