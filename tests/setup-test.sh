#!/bin/sh
# Tests ./setup.sh against throwaway HOME directories: sh tests/setup-test.sh
# Prints PASS or FAIL per check and exits 1 if any check failed. Never touches
# the real HOME.
set -u

REPO=$(cd -P "$(dirname "$0")/.." && pwd -P)
ROOT=${TMPDIR:-/tmp}/guidelines-setup-test.$$
LAYER=.opencode/opencode.json
MARKER='// Generated by pyck-ai/guidelines setup.sh. Do not edit: rerun ./setup.sh. Remove with ./setup.sh uninstall.'
LEGACY1='// Generated by pyck-ai/standards setup.sh, do not edit'
LEGACY2='// Org guidelines layer for opencode: written by hand'
FAILS=0
CASE=0
H=
OUT=
RC=0

pass() { printf 'PASS %s\n' "$1"; }
fail() {
	printf 'FAIL %s\n' "$1"
	FAILS=$((FAILS + 1))
}
# check DESC CMD...: PASS if CMD succeeds.
check() {
	_d=$1
	shift
	if "$@"; then pass "$_d"; else fail "$_d"; fi
}

# new_home: a fresh HOME in $H, the output file in $OUT.
new_home() {
	CASE=$((CASE + 1))
	H=$ROOT/home$CASE
	OUT=$ROOT/out$CASE
	mkdir -p "$H"
}

# setup ARGS...: run setup.sh with HOME=$H; output in $OUT, exit code in $RC.
setup() {
	HOME=$H sh "$REPO/setup.sh" "$@" >"$OUT" 2>&1
	RC=$?
}

snapshot() { ls -lAR "$H"; }
says() { grep -F -q -- "$1" "$OUT"; }
rc_is() { [ "$RC" -eq "$1" ]; }
absent() { ! [ -e "$1" ] && ! [ -L "$1" ]; }
is_link_to() { [ -L "$1" ] && [ "$(readlink "$1")" = "$2" ]; }
first_line_is() { [ "$(head -n 1 "$1")" = "$2" ]; }
is_real_dir() { [ -d "$1" ] && [ ! -L "$1" ]; }
same_text() { [ "$(cat "$1")" = "$2" ]; }
# json_ok FILE: FILE minus its first line is valid JSON.
json_ok() { tail -n +2 "$1" | python3 -c 'import json,sys; json.loads(sys.stdin.read())'; }

# links_ok [SKIP]: every skill is linked into both dirs, except SKIP (a path).
links_ok() {
	for _d in .agents/skills .claude/skills; do
		for _s in $SKILLS; do
			[ "$H/$_d/$_s" = "${1:-}" ] && continue
			is_link_to "$H/$_d/$_s" "$REPO/skills/$_s" || return 1
		done
	done
}
no_links() {
	for _d in .agents/skills .claude/skills; do
		for _s in $SKILLS; do
			absent "$H/$_d/$_s" || return 1
		done
	done
}

SKILLS=
N=0
for _p in "$REPO"/skills/*/; do
	_p=${_p%/}
	SKILLS="$SKILLS ${_p##*/}"
	N=$((N + 1))
done
# shellcheck disable=SC2086
set -- $SKILLS
S1=$1
HAVE_PY=1
command -v python3 >/dev/null 2>&1 || HAVE_PY=0

mkdir -p "$ROOT" || exit 1
trap 'rm -rf "$ROOT"' EXIT

echo "== dry run"
new_home
mkdir -p "$H/.agents/skills"
ln -s "$REPO/skills/gone" "$H/.agents/skills/gone"
before=$(snapshot)
setup --dry-run
after=$(snapshot)
check "exit 0" rc_is 0
check "changes nothing on disk" [ "$before" = "$after" ]
check "says it is a dry run" says "Dry run: install"
check "reports what it would change" says "dry run, install: $((N * 2 + 2)) changed"

echo "== first install"
new_home
setup
check "exit 0" rc_is 0
check "every skill is linked into both dirs" links_ok
check "layer is written" says "wrote     ~/$LAYER"
check "layer starts with the marker" first_line_is "$H/$LAYER" "$MARKER"
if [ "$HAVE_PY" -eq 1 ]; then
	check "layer is valid JSON" json_ok "$H/$LAYER"
else
	printf 'SKIP layer is valid JSON (python3 missing)\n'
fi
check "layer loads AGENTS.md" grep -F -q "\"$REPO/AGENTS.md\"" "$H/$LAYER"
check "layer guards the skill links" grep -F -q "\".agents/skills/$S1/*\": \"ask\"" "$H/$LAYER"

echo "== second install"
setup
check "exit 0" rc_is 0
check "0 changed" says " 0 changed,"

echo "== uninstall"
ln -s "$ROOT/elsewhere" "$H/.agents/skills/foreign"
echo notes >"$H/.claude/skills/notes.txt"
setup uninstall
check "exit 0" rc_is 0
check "our links are gone" no_links
check "our layer is gone" absent "$H/$LAYER"
check "foreign link stays" is_link_to "$H/.agents/skills/foreign" "$ROOT/elsewhere"
check "unmarked file stays" same_text "$H/.claude/skills/notes.txt" notes
setup uninstall
check "second uninstall: exit 0" rc_is 0
check "second uninstall: 0 changed" says " 0 changed,"

echo "== real folder at a target"
new_home
mkdir -p "$H/.agents/skills/$S1"
echo mine >"$H/.agents/skills/$S1/file"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/.agents/skills/$S1 exists and is not a link"
check "folder is untouched" same_text "$H/.agents/skills/$S1/file" mine
check "folder is still a real directory" is_real_dir "$H/.agents/skills/$S1"
check "every other link is made" links_ok "$H/.agents/skills/$S1"
check "layer is still written" [ -f "$H/$LAYER" ]

echo "== foreign symlink at a target"
new_home
mkdir -p "$H/.claude/skills"
ln -s "$ROOT/elsewhere" "$H/.claude/skills/$S1"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/.claude/skills/$S1 links to"
check "foreign link is untouched" is_link_to "$H/.claude/skills/$S1" "$ROOT/elsewhere"
check "every other link is made" links_ok "$H/.claude/skills/$S1"

echo "== stale link into the checkout"
new_home
mkdir -p "$H/.agents/skills" "$H/.claude/skills"
ln -s "$REPO/skills/gone" "$H/.agents/skills/gone"
ln -s "$REPO/skills/gone" "$H/.claude/skills/gone"
setup
check "exit 0" rc_is 0
check "stale link is removed from .agents" absent "$H/.agents/skills/gone"
check "stale link is removed from .claude" absent "$H/.claude/skills/gone"
check "reported as removed" says "removed   ~/.agents/skills/gone"
check "every skill is linked" links_ok

echo "== legacy layer"
for _legacy in "$LEGACY1" "$LEGACY2"; do
	new_home
	mkdir -p "$H/.opencode"
	printf '%s\n{}\n' "$_legacy" >"$H/$LAYER"
	setup
	check "exit 0 (${_legacy%%:*})" rc_is 0
	check "adopted and rewritten (${_legacy%%:*})" says "updated   ~/$LAYER"
	check "now carries the marker (${_legacy%%:*})" first_line_is "$H/$LAYER" "$MARKER"
done

echo "== layer without a marker"
new_home
mkdir -p "$H/.opencode"
echo '{"mine": true}' >"$H/$LAYER"
setup
check "install: exit 1" rc_is 1
check "install: reported as conflict" says "conflict  ~/$LAYER exists and was not generated"
check "install: file is untouched" same_text "$H/$LAYER" '{"mine": true}'
check "install: links are still made" links_ok
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: reported as kept" says "kept      ~/$LAYER"
check "uninstall: file stays" same_text "$H/$LAYER" '{"mine": true}'

echo
if [ "$FAILS" -eq 0 ]; then
	echo "all checks passed"
else
	echo "$FAILS check(s) failed"
	exit 1
fi
