#!/bin/sh
# Tests ./setup.sh against throwaway HOME directories: sh tests/setup-test.sh
# Prints PASS or FAIL per check and exits 1 if any check failed. Never touches
# the real HOME.
set -u

REPO=$(cd -P "$(dirname "$0")/.." && pwd -P)
ROOT=${TMPDIR:-/tmp}/guidelines-setup-test.$$
LAYER=.config/opencode/config.json
USERCFG=.config/opencode/opencode.json
MARKER='// Generated by pyck-ai/guidelines setup.sh. Do not edit: rerun ./setup.sh. Remove with ./setup.sh uninstall.'
LEGACY1='// Generated by pyck-ai/standards setup.sh, do not edit'
LEGACY2='// Org guidelines layer for opencode: written by hand'
SETUP_ENV=
SCRIPT=
FAILS=0
CASE=0
H=
OUT=
RC=0

pass() { printf 'PASS %s\n' "$1"; }
fail() {
	printf 'FAIL %s\n' "$1"
	FAILS=$((FAILS + 1))
}
# check DESC CMD...: PASS if CMD succeeds.
check() {
	_desc=$1
	shift
	if "$@"; then pass "$_desc"; else fail "$_desc"; fi
}

# new_home: a fresh HOME in $H, the output file in $OUT.
new_home() {
	CASE=$((CASE + 1))
	H=$ROOT/home$CASE
	OUT=$ROOT/out$CASE
	mkdir -p "$H"
	SETUP_ENV=
	SCRIPT=
}

# setup ARGS...: run setup.sh with HOME=$H (plus the VAR=value words in
# $SETUP_ENV); output in $OUT, exit code in $RC. $SCRIPT overrides the script.
setup() {
	# shellcheck disable=SC2086
	env HOME="$H" $SETUP_ENV sh "${SCRIPT:-$REPO/setup.sh}" "$@" >"$OUT" 2>&1
	RC=$?
}

snapshot() { ls -lAR "$H"; }
says() { grep -F -q -- "$1" "$OUT"; }
says_line() { grep -F -x -q -- "$1" "$OUT"; }
not() { ! "$@"; }
rc_is() { [ "$RC" -eq "$1" ]; }
absent() { ! [ -e "$1" ] && ! [ -L "$1" ]; }
is_link_to() { [ -L "$1" ] && [ "$(readlink "$1")" = "$2" ]; }
first_line_is() { [ "$(head -n 1 "$1")" = "$2" ]; }
is_real_dir() { [ -d "$1" ] && [ ! -L "$1" ]; }
same_text() { [ "$(cat "$1")" = "$2" ]; }
# json_ok FILE: FILE minus its first line is valid JSON.
json_ok() { tail -n +2 "$1" | python3 -c 'import json,sys; json.loads(sys.stdin.read())'; }

# links_to BASE [SKIP]: every skill is linked into both dirs as BASE/skills/<n>,
# except SKIP (a path).
links_to() {
	for _d in .agents/skills .claude/skills; do
		for _s in $SKILLS; do
			[ "$H/$_d/$_s" = "${2:-}" ] && continue
			is_link_to "$H/$_d/$_s" "$1/skills/$_s" || return 1
		done
	done
}
# links_ok [SKIP]: every skill is linked through ~/.pyck/guidelines.
links_ok() { links_to "$H/.pyck/guidelines" "${1:-}"; }
# links_into_repo: some skill link still points into the real checkout path.
links_into_repo() {
	for _l in "$H"/.agents/skills/* "$H"/.claude/skills/*; do
		case $(readlink "$_l") in "$REPO"/*) return 0 ;; esac
	done
	return 1
}
# plant_links BASE: make those links, as an older install or another checkout would.
plant_links() {
	for _d in .agents/skills .claude/skills; do
		mkdir -p "$H/$_d"
		for _s in $SKILLS; do
			ln -s "$1/skills/$_s" "$H/$_d/$_s"
		done
	done
}
no_links() {
	for _d in .agents/skills .claude/skills; do
		for _s in $SKILLS; do
			absent "$H/$_d/$_s" || return 1
		done
	done
}

SKILLS=
N=0
for _p in "$REPO"/skills/*/; do
	_p=${_p%/}
	SKILLS="$SKILLS ${_p##*/}"
	N=$((N + 1))
done
# shellcheck disable=SC2086
set -- $SKILLS
S1=$1
HAVE_PY=1
command -v python3 >/dev/null 2>&1 || HAVE_PY=0

mkdir -p "$ROOT" || exit 1
trap 'rm -rf "$ROOT"' EXIT

echo "== dry run"
new_home
mkdir -p "$H/.agents/skills"
ln -s "$REPO/skills/gone" "$H/.agents/skills/gone"
before=$(snapshot)
setup --dry-run
after=$(snapshot)
check "exit 0" rc_is 0
check "changes nothing on disk" [ "$before" = "$after" ]
check "says it is a dry run" says "Dry run: install"
check "reports what it would change" says "dry run, install: $((N * 2 + 4)) changed"

echo "== first install"
new_home
setup
check "exit 0" rc_is 0
check "every skill is linked into both dirs" links_ok
check "layer is written" says "wrote     ~/$LAYER"
check "layer starts with the marker" first_line_is "$H/$LAYER" "$MARKER"
if [ "$HAVE_PY" -eq 1 ]; then
	check "layer is valid JSON" json_ok "$H/$LAYER"
else
	printf 'SKIP layer is valid JSON (python3 missing)\n'
fi
check "layer does not load AGENTS.md from the checkout path" not grep -F -q "\"$REPO/AGENTS.md\"" "$H/$LAYER"
check "layer loads AGENTS.md through ~/.pyck/guidelines" grep -F -q "\"$H/.pyck/guidelines/AGENTS.md\"" "$H/$LAYER"
check "layer allows the checkout and ~/.pyck/guidelines" grep -F -q "\"$REPO/*\": \"allow\"" "$H/$LAYER"
check "layer allows ~/.pyck/guidelines" grep -F -q "\"$H/.pyck/guidelines/*\": \"allow\"" "$H/$LAYER"
check "layer guards the checkout" grep -F -q "\"*../${REPO#/}/*\": \"ask\"" "$H/$LAYER"
check "layer guards ~/.pyck/guidelines" grep -F -q "\"*../${H#/}/.pyck/guidelines/*\": \"ask\"" "$H/$LAYER"
check "the .pyck/guidelines path links to the checkout" is_link_to "$H/.pyck/guidelines" "$REPO"
check "reported as linked" says "linked    ~/.pyck/guidelines -> $REPO"
check "layer guards the skill links" grep -F -q "\".agents/skills/$S1/*\": \"ask\"" "$H/$LAYER"

echo "== second install"
setup
check "exit 0" rc_is 0
check "0 changed" says " 0 changed,"
check "the .pyck/guidelines path is ok" says "ok        ~/.pyck/guidelines"

echo "== uninstall"
ln -s "$ROOT/elsewhere" "$H/.agents/skills/foreign"
echo notes >"$H/.claude/skills/notes.txt"
setup uninstall
check "exit 0" rc_is 0
check "our links are gone" no_links
check "our layer is gone" absent "$H/$LAYER"
check "our ~/.pyck/guidelines link is gone" absent "$H/.pyck/guidelines"
check "the .pyck directory itself stays" is_real_dir "$H/.pyck"
check "foreign link stays" is_link_to "$H/.agents/skills/foreign" "$ROOT/elsewhere"
check "unmarked file stays" same_text "$H/.claude/skills/notes.txt" notes
setup uninstall
check "second uninstall: exit 0" rc_is 0
check "second uninstall: 0 changed" says " 0 changed,"

echo "== real folder at ~/.pyck/guidelines"
new_home
mkdir -p "$H/.pyck/guidelines"
echo mine >"$H/.pyck/guidelines/file"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/.pyck/guidelines exists and is not a link"
check "folder is untouched" same_text "$H/.pyck/guidelines/file" mine
check "folder is still a real directory" is_real_dir "$H/.pyck/guidelines"
check "explains the fix" says "uninstall"
check "nothing else is installed" no_links
check "no layer is written" absent "$H/$LAYER"
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: reported as kept" says "kept      ~/.pyck/guidelines"
check "uninstall: folder stays" same_text "$H/.pyck/guidelines/file" mine

echo "== foreign link at ~/.pyck/guidelines"
new_home
mkdir -p "$H/.pyck"
ln -s "$ROOT/elsewhere" "$H/.pyck/guidelines"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/.pyck/guidelines links to"
check "foreign link is untouched" is_link_to "$H/.pyck/guidelines" "$ROOT/elsewhere"
check "nothing else is installed" no_links
check "no layer is written" absent "$H/$LAYER"
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: foreign link stays" is_link_to "$H/.pyck/guidelines" "$ROOT/elsewhere"

echo "== ~/.pyck/guidelines is this checkout"
# A link to the repo stands in for a clone made at ~/.pyck/guidelines: the
# path resolves to the repo, so setup.sh creates nothing there.
new_home
mkdir -p "$H/.pyck"
ln -s "$REPO" "$H/.pyck/guidelines"
setup
check "exit 0" rc_is 0
check "reported as ok" says "ok        ~/.pyck/guidelines"
check "link is unchanged" is_link_to "$H/.pyck/guidelines" "$REPO"
check "layer names ~/.pyck/guidelines/AGENTS.md" grep -F -q "\"$H/.pyck/guidelines/AGENTS.md\"" "$H/$LAYER"

echo "== ~/.pyck/guidelines resolves to this checkout"
# The link text differs from $REPO but resolves to it, as a clone would.
new_home
mkdir -p "$H/.pyck"
ln -s "$REPO/." "$H/.pyck/guidelines"
setup
check "exit 0" rc_is 0
check "reported as this checkout" says "ok        ~/.pyck/guidelines (this checkout)"
check "link is unchanged" is_link_to "$H/.pyck/guidelines" "$REPO/."
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: not ours by text, so kept" says "kept      ~/.pyck/guidelines"

echo "== migration from links to the checkout path"
new_home
plant_links "$REPO"
setup
check "exit 0" rc_is 0
check "old links are relinked" says "relinked  ~/.agents/skills/$S1 -> ~/.pyck/guidelines/skills/$S1"
check "every skill now links through ~/.pyck/guidelines" links_ok
check "no skill link points at the checkout path" not links_into_repo
check "the home link is made" is_link_to "$H/.pyck/guidelines" "$REPO"
setup
check "re-run: 0 changed" says " 0 changed,"

echo "== clone in place"
# The checkout itself lives at ~/.pyck/guidelines: nothing is linked there.
new_home
mkdir -p "$H/.pyck/guidelines"
cp -R "$REPO/skills" "$H/.pyck/guidelines/skills"
cp "$REPO/setup.sh" "$H/.pyck/guidelines/setup.sh"
SCRIPT=$H/.pyck/guidelines/setup.sh
setup
check "exit 0" rc_is 0
check "reported as this checkout" says "ok        ~/.pyck/guidelines (this checkout)"
check "still a real directory" is_real_dir "$H/.pyck/guidelines"
check "every skill links through ~/.pyck/guidelines" links_ok
check "layer loads AGENTS.md through ~/.pyck/guidelines" grep -F -q "\"$H/.pyck/guidelines/AGENTS.md\"" "$H/$LAYER"
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: our links are gone" no_links
check "uninstall: the clone stays" is_real_dir "$H/.pyck/guidelines"
check "uninstall: reported as kept" says "kept      ~/.pyck/guidelines"

echo "== ~/.pyck/guidelines belongs to another checkout"
new_home
mkdir -p "$ROOT/other/skills" "$H/.pyck"
for _s in $SKILLS; do mkdir -p "$ROOT/other/skills/$_s"; done
ln -s "$ROOT/other" "$H/.pyck/guidelines"
plant_links "$H/.pyck/guidelines"
before=$(snapshot)
setup
after=$(snapshot)
check "install: exit 1" rc_is 1
check "install: reported as conflict" says "conflict  ~/.pyck/guidelines links to"
check "install: changes nothing" [ "$before" = "$after" ]
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: the link stays" is_link_to "$H/.pyck/guidelines" "$ROOT/other"
check "uninstall: links through it stay" links_ok
check "uninstall: nothing removed" says " 0 changed,"

echo "== an exported PYCK_HOME is ignored"
new_home
SETUP_ENV="PYCK_HOME=$H/custom"
setup
check "exit 0" rc_is 0
check "the home link is still ~/.pyck/guidelines" is_link_to "$H/.pyck/guidelines" "$REPO"
check "the exported directory is not created" absent "$H/custom"
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: the home link is gone" absent "$H/.pyck/guidelines"
check "uninstall: the exported directory is not created" absent "$H/custom"

echo "== real folder at a target"
new_home
mkdir -p "$H/.agents/skills/$S1"
echo mine >"$H/.agents/skills/$S1/file"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/.agents/skills/$S1 exists and is not a link"
check "folder is untouched" same_text "$H/.agents/skills/$S1/file" mine
check "folder is still a real directory" is_real_dir "$H/.agents/skills/$S1"
check "every other link is made" links_ok "$H/.agents/skills/$S1"
check "layer is still written" [ -f "$H/$LAYER" ]

echo "== foreign symlink at a target"
new_home
mkdir -p "$H/.claude/skills"
ln -s "$ROOT/elsewhere" "$H/.claude/skills/$S1"
setup
check "exit 1" rc_is 1
check "reported as conflict" says "conflict  ~/.claude/skills/$S1 links to"
check "foreign link is untouched" is_link_to "$H/.claude/skills/$S1" "$ROOT/elsewhere"
check "every other link is made" links_ok "$H/.claude/skills/$S1"

echo "== stale link into the checkout"
new_home
mkdir -p "$H/.agents/skills" "$H/.claude/skills"
ln -s "$REPO/skills/gone" "$H/.agents/skills/gone"
ln -s "$REPO/skills/gone" "$H/.claude/skills/gone"
setup
check "exit 0" rc_is 0
check "stale link is removed from .agents" absent "$H/.agents/skills/gone"
check "stale link is removed from .claude" absent "$H/.claude/skills/gone"
check "reported as removed" says "removed   ~/.agents/skills/gone"
check "every skill is linked" links_ok

echo "== legacy layer"
for _legacy in "$LEGACY1" "$LEGACY2"; do
	new_home
	mkdir -p "$H/.config/opencode"
	printf '%s\n{}\n' "$_legacy" >"$H/$LAYER"
	setup
	check "exit 0 (${_legacy%%:*})" rc_is 0
	check "adopted and rewritten (${_legacy%%:*})" says "updated   ~/$LAYER"
	check "now carries the marker (${_legacy%%:*})" first_line_is "$H/$LAYER" "$MARKER"
done

echo "== layer without a marker"
new_home
mkdir -p "$H/.config/opencode"
echo '{"mine": true}' >"$H/$LAYER"
setup
check "install: exit 1" rc_is 1
check "install: reported as conflict" says "conflict  ~/$LAYER exists and was not generated"
check "install: file is untouched" same_text "$H/$LAYER" '{"mine": true}'
check "install: links are still made" links_ok
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: reported as kept" says "kept      ~/$LAYER"
check "uninstall: file stays" same_text "$H/$LAYER" '{"mine": true}'

echo "== seeding opencode.json"
new_home
setup
check "exit 0" rc_is 0
check "opencode.json is seeded" says "seeded    ~/$USERCFG"
check "seed is the schema only" same_text "$H/$USERCFG" '{ "$schema": "https://opencode.ai/config.json" }'
check "seed has no marker" not first_line_is "$H/$USERCFG" "$MARKER"
setup
check "re-run: exit 0" rc_is 0
check "re-run: 0 changed" says " 0 changed,"
echo '{ "theme": "mine" }' >"$H/$USERCFG"
setup
check "edited seed is never overwritten" same_text "$H/$USERCFG" '{ "theme": "mine" }'
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: layer is gone" absent "$H/$LAYER"
check "uninstall: opencode.json stays" same_text "$H/$USERCFG" '{ "theme": "mine" }'

echo "== no seeding when opencode.jsonc exists"
new_home
mkdir -p "$H/.config/opencode"
echo '{}' >"$H/.config/opencode/opencode.jsonc"
setup
check "exit 0" rc_is 0
check "layer is written" says "wrote     ~/$LAYER"
check "no opencode.json is seeded" absent "$H/$USERCFG"
check "opencode.jsonc is untouched" same_text "$H/.config/opencode/opencode.jsonc" '{}'

echo "== no seeding when opencode.json is a link"
new_home
mkdir -p "$H/.config/opencode"
printf '{}\n' >"$ROOT/target.json"
ln -s "$ROOT/target.json" "$H/$USERCFG"
setup
check "exit 0" rc_is 0
check "the link is untouched" is_link_to "$H/$USERCFG" "$ROOT/target.json"
check "no seed is reported" not says "seeded"
check "no instructions note" not says "note"

echo "== instructions note"
for _f in opencode.json opencode.jsonc; do
	new_home
	mkdir -p "$H/.config/opencode"
	printf '{\n  "instructions": ["x.md"]\n}\n' >"$H/.config/opencode/$_f"
	setup
	check "exit 0 ($_f)" rc_is 0
	check "note names the file ($_f)" says "note      ~/.config/opencode/$_f sets \"instructions\""
	check "note names the org AGENTS.md ($_f)" says "~/.pyck/guidelines/AGENTS.md"
	check "the user file is untouched ($_f)" same_text "$H/.config/opencode/$_f" '{
  "instructions": ["x.md"]
}'
done

echo "== foreign config.json"
new_home
mkdir -p "$H/.config/opencode"
echo '{"mine": true}' >"$H/$LAYER"
setup
check "install: exit 1" rc_is 1
check "install: reported as conflict" says "conflict  ~/$LAYER exists and was not generated"
check "install: file is untouched" same_text "$H/$LAYER" '{"mine": true}'

echo "== XDG_CONFIG_HOME"
new_home
SETUP_ENV="XDG_CONFIG_HOME=$H/xdg"
setup
check "exit 0" rc_is 0
check "layer is written below XDG_CONFIG_HOME" first_line_is "$H/xdg/opencode/config.json" "$MARKER"
check "opencode.json is seeded there" [ -f "$H/xdg/opencode/opencode.json" ]
check "nothing is written to ~/.config" absent "$H/.config"
setup uninstall
check "uninstall: exit 0" rc_is 0
check "uninstall: layer is gone" absent "$H/xdg/opencode/config.json"

echo "== migration from ~/.opencode"
echo "-- only opencode's own files"
new_home
mkdir -p "$H/.opencode/node_modules/x"
printf '%s\n{}\n' "$MARKER" >"$H/.opencode/opencode.json"
for _f in package.json package-lock.json bun.lock .gitignore; do echo x >"$H/.opencode/$_f"; done
before=$(snapshot)
setup --dry-run
check "dry run: exit 0" rc_is 0
check "dry run: changes nothing but the plan" [ "$before" = "$(snapshot)" ]
check "dry run: reports the directory" says_line "removed   ~/.opencode"
setup
check "exit 0" rc_is 0
check "old layer is reported removed" says "removed   ~/.opencode/opencode.json"
check "directory is reported removed" says_line "removed   ~/.opencode"
check "directory is gone" absent "$H/.opencode"
check "new layer is written" first_line_is "$H/$LAYER" "$MARKER"
setup
check "re-run: 0 changed" says " 0 changed,"
echo "-- a foreign file"
new_home
mkdir -p "$H/.opencode"
printf '%s\n{}\n' "$MARKER" >"$H/.opencode/opencode.json"
echo x >"$H/.opencode/package.json"
echo mine >"$H/.opencode/agents.md"
setup
check "exit 0" rc_is 0
check "our old layer is gone" absent "$H/.opencode/opencode.json"
check "directory is kept" says "kept      ~/.opencode (also holds: agents.md)"
check "foreign file stays" same_text "$H/.opencode/agents.md" mine
check "auto-install file stays" [ -f "$H/.opencode/package.json" ]
echo "-- a legacy layer"
new_home
mkdir -p "$H/.opencode"
printf '%s\n{}\n' "$LEGACY1" >"$H/.opencode/opencode.json"
setup
check "exit 0" rc_is 0
check "legacy layer is removed" absent "$H/.opencode"
echo "-- a foreign opencode.json"
new_home
mkdir -p "$H/.opencode"
echo '{"mine": true}' >"$H/.opencode/opencode.json"
setup
check "exit 0" rc_is 0
check "foreign file stays" same_text "$H/.opencode/opencode.json" '{"mine": true}'
check "directory is kept" says "kept      ~/.opencode (also holds: opencode.json)"
echo "-- uninstall"
new_home
setup
mkdir -p "$H/.opencode"
printf '%s\n{}\n' "$MARKER" >"$H/.opencode/opencode.json"
setup uninstall
check "exit 0" rc_is 0
check "old layer is removed" absent "$H/.opencode/opencode.json"
check "new layer is removed" absent "$H/$LAYER"

echo
if [ "$FAILS" -eq 0 ]; then
	echo "all checks passed"
else
	echo "$FAILS check(s) failed"
	exit 1
fi
