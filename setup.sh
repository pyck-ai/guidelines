#!/bin/sh
# Installs the org guidelines for the current user. Everything is installed
# THROUGH ~/.pyck/guidelines, never at the checkout's own path:
#   ~/.pyck/guidelines   the home of this repo. Clone straight into it, or keep
#               the checkout (or a worktree) elsewhere and let setup.sh link
#               it there. Agent files name paths under it (never URLs), so
#               every agent finds the rules at one local path, and switching
#               worktree is one repointed symlink with no re-run.
#   skills/*/   linked (as ~/.pyck/guidelines/skills/*) by the metadata.harness
#               tag in each SKILL.md frontmatter: generic into ~/.agents/skills/
#               (opencode reads that dir, as its environment turns off only
#               Claude Code's files, ~/.claude, and so does pi), opencode into
#               opencode's skills dir ~/.config/opencode/skills/ (under
#               $XDG_CONFIG_HOME when set). A skill without a valid tag is a
#               conflict and is not linked. Claude Code is not a target; install
#               and uninstall remove our old links from ~/.claude/skills.
#               Foreign entries and the dirs themselves stay.
#   AGENTS.md   not wired in: setup.sh does not configure any harness. The
#               harness config must load ~/.pyck/guidelines/AGENTS.md itself
#               (README, "Getting started", has the opencode line). Install and
#               uninstall remove the files earlier versions generated, when they
#               are still ours: ~/.config/opencode/config.json (under
#               $XDG_CONFIG_HOME when set) and ~/.opencode/opencode.json. Install
#               also removes ~/.opencode when nothing but opencode's own files
#               is left in it.
#
#   ./setup.sh [install] [--dry-run]    link and write, safe to re-run (default)
#   ./setup.sh uninstall [--dry-run]    remove only our links and our old layers
#
# Conflict rule: a path that exists and is not ours is skipped, reported as
# "conflict" and never touched; the exit code is then 1. "Ours" is a symlink
# into this checkout (or through ~/.pyck/guidelines while that is this
# checkout), or a generated file whose first line is MARKER. A ~/.pyck/guidelines
# that is something else stops the install before it links anything. Uninstall
# removes the ~/.pyck/guidelines link last and keeps ~/.pyck itself, which
# other repositories use.
# The common block below is shared verbatim; it keeps helpers a repo may not use.
set -eu

PYCK_NAME=guidelines
REPO=$(cd -P "$(dirname "$0")" && pwd -P)
MARKER='// Generated by pyck-ai/guidelines setup.sh. Do not edit: rerun ./setup.sh. Remove with ./setup.sh uninstall.'
LEGACY_MARKERS='// Generated by pyck-ai/standards setup.sh
// Org guidelines layer for opencode'

# --- setup.sh common block ---------------------------------------------------
# Identical in every repo's setup.sh (pyck-ai/guidelines, michaelkrupp/opencode,
# michaelkrupp/litellm); change it in all of them.
# POSIX sh only: no `local`, arrays, [[ ]], `readlink -f`, `ln -n`, `install`
# or `mktemp`. A script sets REPO, PYCK_NAME (this repo's name under ~/.pyck),
# MARKER (may be empty) and LEGACY_MARKERS (newline list, may be empty) before
# calling `common_init "$@"`, and ends with `prune` and `common_finish`.
# A script that calls `link_skills REL` also sets SKILLS_GENERIC (the dir for
# skills tagged `harness: generic`, e.g. ~/.agents/skills) and SKILLS_OPENCODE
# (the dir for `harness: opencode`, opencode's config skills dir) before it.
#
# Every repo has a home at $PYCK_HOME/$PYCK_NAME (HOME_LINK). PYCK_HOME is
# always ~/.pyck and not overridable, because agent files name that literal
# path. The home is a clone placed there, or a symlink to the checkout.
# common_init makes the symlink on install and stops with exit 1 when
# something else is there, because every link would point into another
# checkout. common_finish removes the symlink last on uninstall
# (a clone or a foreign link stays; $PYCK_HOME itself always stays). A script
# links from $SRC (= HOME_LINK), never from $REPO, so that switching to
# another worktree is one repointed symlink and no re-run.
# shellcheck disable=SC2012,SC2329 # ls is only the readlink fallback; no script uses every helper
{

MODE=install
DRY=0
N_CHANGED=0
N_OK=0
N_CONFLICT=0
MANAGED_DIRS=''
PLANNED=''
HOME_STATE=absent

common_usage() {
	cat <<EOF
Usage: ./setup.sh [install|uninstall] [--dry-run]

  install     link this checkout into place (default); safe to re-run
  uninstall   remove what install made; user data stays
  --dry-run   print what would happen, change nothing

Each line is "<state> <path>". States: ok, linked, relinked, wrote,
updated, seeded, enabled, disabled, removed, kept, absent, conflict.
A conflict (a path that exists and is not ours) is skipped, never touched.
Exit codes: 0 ok, 1 a conflict or a failed step, 2 usage error.
EOF
}

common_init() {
	if [ -z "${PYCK_NAME:-}" ]; then
		printf 'setup.sh: PYCK_NAME is not set\n' >&2
		exit 2
	fi
	PYCK_HOME=$HOME/.pyck
	HOME_LINK=$PYCK_HOME/$PYCK_NAME
	SRC=$HOME_LINK
	for _arg in "$@"; do
		case $_arg in
		install | uninstall) MODE=$_arg ;;
		--dry-run | -n) DRY=1 ;;
		-h | --help)
			common_usage
			exit 0
			;;
		*)
			printf 'setup.sh: unknown argument: %s\n' "$_arg" >&2
			common_usage >&2
			exit 2
			;;
		esac
	done
	if [ "$DRY" -eq 1 ]; then
		printf 'Dry run: %s %s, nothing is changed.\n' "$MODE" "$(tilde "$REPO")"
	else
		printf '%s %s\n' "$MODE" "$(tilde "$REPO")"
	fi
	home_check
	if [ "$MODE" = install ]; then link_home; fi
}

# tilde PATH: PATH with $HOME shown as ~.
tilde() {
	case $1 in
	"$HOME") printf '~' ;;
	"$HOME"/*) printf '~%s' "${1#"$HOME"}" ;;
	*) printf '%s' "$1" ;;
	esac
}

say() { printf '%-9s %s\n' "$1" "$2"; }
changed() {
	say "$1" "$2"
	N_CHANGED=$((N_CHANGED + 1))
}
ok() {
	say "$1" "$2"
	N_OK=$((N_OK + 1))
}
conflict() {
	say conflict "$1"
	N_CONFLICT=$((N_CONFLICT + 1))
}

# run CMD...: run CMD unless this is a dry run.
run() {
	if [ "$DRY" -eq 0 ]; then "$@"; fi
}

# link_target LINK: where the symlink LINK points (POSIX readlink, ls fallback).
link_target() {
	readlink "$1" 2>/dev/null || ls -ld "$1" | sed 's/.* -> //'
}

# home_check: classify HOME_LINK into HOME_STATE: symlink (a symlink to exactly
# REPO), here (a path that resolves to REPO, e.g. a clone made there), absent,
# foreign-link (a symlink elsewhere) or foreign (any other existing path).
home_check() {
	if [ -L "$HOME_LINK" ] && [ "$(link_target "$HOME_LINK")" = "$REPO" ]; then
		HOME_STATE=symlink
	elif [ -d "$HOME_LINK" ] && [ "$(cd -P "$HOME_LINK" && pwd -P)" = "$REPO" ]; then
		HOME_STATE=here
	elif [ -L "$HOME_LINK" ]; then
		HOME_STATE=foreign-link
	elif [ -e "$HOME_LINK" ]; then
		HOME_STATE=foreign
	else
		HOME_STATE=absent
	fi
}

# link_home (install): make HOME_LINK a link to this checkout. A conflict
# stops the script before anything else is installed.
link_home() {
	case $HOME_STATE in
	symlink) ok ok "$(tilde "$HOME_LINK")" ;;
	here) ok ok "$(tilde "$HOME_LINK") (this checkout)" ;;
	absent)
		run mkdir -p "$PYCK_HOME"
		run ln -s "$REPO" "$HOME_LINK"
		changed linked "$(tilde "$HOME_LINK") -> $(tilde "$REPO")"
		;;
	foreign-link) conflict "$(tilde "$HOME_LINK") links to $(tilde "$(link_target "$HOME_LINK")"), not to this checkout" ;;
	*) conflict "$(tilde "$HOME_LINK") exists and is not a link" ;;
	esac
	if [ "$N_CONFLICT" -gt 0 ]; then
		printf 'Every link would point into another checkout. Repoint or remove %s, or run the other checkout'\''s ./setup.sh uninstall, then re-run.\n' "$(tilde "$HOME_LINK")" >&2
		exit 1
	fi
}

# unlink_home (uninstall): remove HOME_LINK if it is a link to this checkout.
# A real directory (a clone) or a foreign link stays.
unlink_home() {
	case $HOME_STATE in
	symlink)
		run rm -f "$HOME_LINK"
		changed removed "$(tilde "$HOME_LINK")"
		;;
	absent) ok absent "$(tilde "$HOME_LINK")" ;;
	*) ok kept "$(tilde "$HOME_LINK") (not a link to this checkout)" ;;
	esac
}

# is_ours TARGET: TARGET lies inside this checkout, or inside HOME_LINK while
# that is this checkout (or, on install, is about to be made so).
is_ours() {
	case $1 in "$REPO"/*) return 0 ;; esac
	case $1 in "$HOME_LINK"/*)
		case $HOME_STATE in
		symlink | here) return 0 ;;
		absent) [ "$MODE" = install ] && return 0 ;;
		esac
		;;
	esac
	return 1
}

# manage DIR: install prunes stale links into this checkout from DIR,
# uninstall removes all of them.
manage() {
	case "
$MANAGED_DIRS
" in *"
$1
"*) return 0 ;; esac
	MANAGED_DIRS="$MANAGED_DIRS
$1"
}

plan() {
	PLANNED="$PLANNED
$1"
}

planned() {
	case "
$PLANNED
" in *"
$1
"*) return 0 ;; esac
	return 1
}

# link SRC DST: make DST a symlink to SRC (install only).
link() {
	_src=$1
	_dst=$2
	plan "$_dst"
	if [ -L "$_dst" ]; then
		_cur=$(link_target "$_dst")
		if [ "$_cur" = "$_src" ]; then
			ok ok "$(tilde "$_dst")"
		elif is_ours "$_cur"; then
			run rm -f "$_dst"
			run ln -s "$_src" "$_dst"
			changed relinked "$(tilde "$_dst") -> $(tilde "$_src")"
		else
			conflict "$(tilde "$_dst") links to $(tilde "$_cur"), not to this checkout"
		fi
	elif [ -e "$_dst" ]; then
		conflict "$(tilde "$_dst") exists and is not a link"
	else
		run mkdir -p "$(dirname "$_dst")"
		run ln -s "$_src" "$_dst"
		changed linked "$(tilde "$_dst") -> $(tilde "$_src")"
	fi
}

# skill_harness DIR: the metadata.harness value of DIR/SKILL.md, quotes and a
# trailing comment stripped; nothing when there is none. Reads only the
# frontmatter (the lines between the first two `---` lines), and only a
# `harness:` line indented under a `metadata:` line.
skill_harness() {
	awk -v q="'" '
		NR == 1 { if ($0 !~ /^---[[:blank:]]*$/) exit; next }
		/^---[[:blank:]]*$/ { exit }
		/^metadata:[[:blank:]]*(#.*)?$/ { meta = 1; next }
		/^[^[:blank:]#]/ { meta = 0 }
		meta && /^[[:blank:]]+harness:/ {
			v = $0
			sub(/^[[:blank:]]+harness:[[:blank:]]*/, "", v)
			sub(/[[:blank:]]+#.*$/, "", v)
			sub(/[[:blank:]]+$/, "", v)
			if (v ~ /^".*"$/ || (substr(v, 1, 1) == q && substr(v, length(v)) == q && length(v) > 1)) v = substr(v, 2, length(v) - 2)
			if (v != "") print v
			exit
		}
	' "$1/SKILL.md"
}

# skill_dest HARNESS: the dir a skill with that harness is linked into
# (SKILLS_GENERIC for generic, SKILLS_OPENCODE for opencode); status 1 and no
# output for anything else.
skill_dest() {
	case $1 in
	generic) printf '%s\n' "$SKILLS_GENERIC" ;;
	opencode) printf '%s\n' "$SKILLS_OPENCODE" ;;
	*) return 1 ;;
	esac
}

# link_skills REL: link every $REPO/REL/<name>/ that holds a SKILL.md, as
# $SRC/REL/<name>, into the dir its metadata.harness names (see skill_dest). A
# missing or unknown harness is a conflict and the skill is not linked. Both
# dirs are managed, in every mode, so that prune removes a link whose harness
# changed (and, on uninstall, all of them). Call it on install and uninstall.
link_skills() {
	manage "$SKILLS_GENERIC"
	manage "$SKILLS_OPENCODE"
	[ "$MODE" = install ] || return 0
	for _sd in "$REPO/$1"/*/; do
		[ -f "${_sd}SKILL.md" ] || continue
		_sd=${_sd%/}
		_sn=${_sd##*/}
		_sh=$(skill_harness "$_sd")
		if _sdir=$(skill_dest "$_sh"); then
			link "$SRC/$1/$_sn" "$_sdir/$_sn"
		elif [ -z "$_sh" ]; then
			conflict "$1/$_sn/SKILL.md has no metadata.harness (generic or opencode), skill not linked"
		else
			conflict "$1/$_sn/SKILL.md has unknown metadata.harness \"$_sh\" (generic or opencode), skill not linked"
		fi
	done
}

# is_marked FILE: FILE's first line is MARKER or starts with a LEGACY_MARKERS line.
is_marked() {
	_first=$(head -n 1 "$1")
	[ -n "$MARKER" ] && [ "$_first" = "$MARKER" ] && return 0
	_ifs=$IFS
	IFS='
'
	for _m in $LEGACY_MARKERS; do
		case $_first in "$_m"*)
			IFS=$_ifs
			return 0
			;;
		esac
	done
	IFS=$_ifs
	return 1
}

# write_marked DST CONTENT: DST is a generated file whose first line is MARKER.
write_marked() {
	_dst=$1
	_content=$2
	plan "$_dst"
	if [ -L "$_dst" ]; then
		conflict "$(tilde "$_dst") is a link, expected a file generated by this script"
	elif [ -f "$_dst" ]; then
		if ! is_marked "$_dst"; then
			conflict "$(tilde "$_dst") exists and was not generated by this script"
		elif [ "$(cat "$_dst")" = "$_content" ]; then
			ok ok "$(tilde "$_dst")"
		else
			if [ "$DRY" -eq 0 ]; then printf '%s\n' "$_content" >"$_dst"; fi
			changed updated "$(tilde "$_dst")"
		fi
	elif [ -e "$_dst" ]; then
		conflict "$(tilde "$_dst") exists and is not a regular file"
	else
		run mkdir -p "$(dirname "$_dst")"
		if [ "$DRY" -eq 0 ]; then printf '%s\n' "$_content" >"$_dst"; fi
		changed wrote "$(tilde "$_dst")"
	fi
}

# remove_marked DST: uninstall a generated file, only if it carries our marker.
remove_marked() {
	if [ -L "$1" ] || { [ -e "$1" ] && ! { [ -f "$1" ] && is_marked "$1"; }; }; then
		ok kept "$(tilde "$1") (not generated by this script)"
	elif [ -f "$1" ]; then
		run rm -f "$1"
		changed removed "$(tilde "$1")"
	else
		ok absent "$(tilde "$1")"
	fi
}

# seed_once DST SRC: copy SRC to DST with mode 0600 unless DST exists (user data).
seed_once() {
	if [ -e "$1" ] || [ -L "$1" ]; then
		ok kept "$(tilde "$1") (user data, never overwritten)"
	else
		run mkdir -p "$(dirname "$1")"
		run cp "$2" "$1"
		run chmod 600 "$1"
		changed seeded "$(tilde "$1") from $(tilde "$2")"
	fi
}

# prune: in every managed dir, remove links into this checkout that install
# did not plan (all of them on uninstall). Foreign entries are never touched.
prune() {
	_ifs=$IFS
	IFS='
'
	for _dir in $MANAGED_DIRS; do
		[ -d "$_dir" ] || continue
		for _p in "$_dir"/* "$_dir"/.[!.]*; do
			[ -L "$_p" ] || continue
			is_ours "$(link_target "$_p")" || continue
			if [ "$MODE" = install ] && planned "$_p"; then continue; fi
			run rm -f "$_p"
			changed removed "$(tilde "$_p")"
		done
	done
	IFS=$_ifs
}

# common_finish: on uninstall remove HOME_LINK last (call after prune), then
# print the summary and exit.
common_finish() {
	if [ "$MODE" = uninstall ]; then unlink_home; fi
	_what="$MODE: $N_CHANGED changed, $N_OK ok, $N_CONFLICT conflicts"
	if [ "$DRY" -eq 1 ]; then _what="dry run, $_what"; fi
	printf '%s\n' "$_what"
	if [ "$N_CONFLICT" -gt 0 ]; then
		printf 'Resolve the conflicts above by hand, then re-run.\n' >&2
		exit 1
	fi
	exit 0
}
}
# --- end of setup.sh common block --------------------------------------------

CONFIG_DIR=${XDG_CONFIG_HOME:-$HOME/.config}/opencode
# setup.sh no longer writes any harness config. Two files it generated before
# are removed when they are still ours (first line is a marker, not a link):
# the layer ~/.config/opencode/config.json and, before that,
# ~/.opencode/opencode.json (opencode loads that only for sessions under $HOME).
OLD_CONFIG=$CONFIG_DIR/config.json
OLD_DIR=$HOME/.opencode
OLD_LAYER=$OLD_DIR/opencode.json
# link_skills (common block) sorts skills by their metadata.harness tag.
SKILLS_GENERIC=$HOME/.agents/skills
SKILLS_OPENCODE=$CONFIG_DIR/skills
# Where skills used to be linked. Kept managed, with nothing placed in it, so
# that prune removes our links there. The dir itself is never removed.
OLD_SKILL_DIRS=$HOME/.claude/skills

# drop_generated FILE: remove FILE if it is a generated file of ours (a regular
# file, not a link, whose first line is a marker); status 1 when it is not.
# Anything else at that path, including a user's own file, is left alone.
drop_generated() {
	if [ -f "$1" ] && [ ! -L "$1" ] && is_marked "$1"; then
		run rm -f "$1"
		changed removed "$(tilde "$1")"
		return 0
	fi
	return 1
}

# drop_old_layers: remove the generated files of earlier versions.
# OLD_DROPPED=1 when ~/.opencode/opencode.json is (or, on a dry run, would be) gone.
OLD_DROPPED=0
drop_old_layers() {
	drop_generated "$OLD_CONFIG" || true
	if drop_generated "$OLD_LAYER"; then OLD_DROPPED=1; fi
}

# drop_old_dir: remove ~/.opencode if it holds nothing but what opencode
# installs by itself: node_modules, package.json, package-lock.json, bun.lock
# and .gitignore (its plugin install). opencode recreates those in every
# .opencode directory it sees, so they would keep the directory alive for good.
# Anything else in there is the user's: the directory stays.
drop_old_dir() {
	[ -d "$OLD_DIR" ] && [ ! -L "$OLD_DIR" ] || return 0
	_foreign=''
	for _p in "$OLD_DIR"/* "$OLD_DIR"/.[!.]*; do
		[ -e "$_p" ] || [ -L "$_p" ] || continue
		case ${_p##*/} in
		node_modules | package.json | package-lock.json | bun.lock | .gitignore) ;;
		*)
			if [ "$OLD_DROPPED" -eq 1 ] && [ "$_p" = "$OLD_LAYER" ]; then continue; fi
			_foreign="$_foreign ${_p##*/}"
			;;
		esac
	done
	if [ -n "$_foreign" ]; then
		ok kept "$(tilde "$OLD_DIR") (also holds:$_foreign)"
	else
		run rm -rf "$OLD_DIR"
		changed removed "$(tilde "$OLD_DIR")"
	fi
}

common_init "$@"
manage "$OLD_SKILL_DIRS"
link_skills skills
drop_old_layers
if [ "$MODE" = install ]; then drop_old_dir; fi
prune
common_finish
